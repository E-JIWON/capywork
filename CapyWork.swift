let moonPixels: [(Int, Int)] = [(2, 0), (3, 0), (1, 1), (1, 2), (2, 3), (3, 3)]

func poseRows(_ p: Pose) -> [String] {
    switch p {
    case .swim(let i, _): return swimFrames[i % swimFrames.count]
    case .flail(let i): return flailFrames[i % flailFrames.count]
    case .chew(let i): return chewFrames[i % chewFrames.count]
    case .roll(let i, _): return rollFrames[i % rollFrames.count]
    case .toss(let i): return tossFrames[min(i, tossFrames.count - 1)]
    case .sleep: return sleepRows
    }
}

func pixelColor(_ c: Character) -> NSColor {
    switch c {
    case "d": return NSColor(srgbRed: 0.45, green: 0.29, blue: 0.17, alpha: 1)  // outline
    case "x": return NSColor(srgbRed: 0.2, green: 0.12, blue: 0.08, alpha: 1)   // eye, nose
    case "p": return NSColor(srgbRed: 0.95, green: 0.55, blue: 0.55, alpha: 1)  // blush
    case "o": return .systemOrange                                              // yuzu
    case "O": return NSColor(srgbRed: 1, green: 0.42, blue: 0, alpha: 1)        // vivid yuzu (needs approval)
    case "h": return NSColor(srgbRed: 1, green: 0.9, blue: 0.6, alpha: 1)       // yuzu shine
    case "l", "g": return .systemGreen                                          // leaf, grass
    case "w": return .systemTeal                                                // water
    case "s", "m": return NSColor(srgbRed: 1, green: 0.85, blue: 0.3, alpha: 1)  // sparkle, moon
    case "z": return .labelColor
    default: return NSColor(srgbRed: 0.76, green: 0.55, blue: 0.36, alpha: 1)   // fur
    }
}

let px: CGFloat = 1.5   // 3 device px on Retina → crisp
let catW = 26 * px, catH = 15 * px  // 39×22.5pt

func menuIcon(_ poses: [Pose], more: Int) -> NSImage {
    let gap: CGFloat = 3
    let moreText = more > 0 ? "+\(more)" as NSString : nil
    let attrs: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 11, weight: .semibold), .foregroundColor: NSColor.labelColor]
    let moreW = moreText.map { $0.size(withAttributes: attrs).width + gap } ?? 0
    let w = CGFloat(poses.count) * catW + CGFloat(poses.count - 1) * gap + moreW
    let img = NSImage(size: NSSize(width: w, height: catH), flipped: true) { _ in
        for (i, pose) in poses.enumerated() {
            let ox = CGFloat(i) * (catW + gap)
            var blink = false
            if case .roll(let f, true) = pose { blink = f % 2 == 1 }  // neglected approval: yuzu flashes red
            for (y, row) in poseRows(pose).enumerated() {
                for (x, c) in row.enumerated() where c != "." {
                    (blink && c == "O" ? NSColor.systemRed : pixelColor(c)).setFill()
                    NSRect(x: ox + CGFloat(x) * px, y: CGFloat(y) * px, width: px, height: px).fill()
                }
            }
            if case .swim(_, true) = pose {
                pixelColor("m").setFill()
                for (x, y) in moonPixels { NSRect(x: ox + CGFloat(x) * px, y: CGFloat(y) * px, width: px, height: px).fill() }
            }
        }
        moreText?.draw(at: NSPoint(x: w - moreW + gap, y: (catH - 14) / 2), withAttributes: attrs)
        return true
    }
    img.isTemplate = false
    return img
}

