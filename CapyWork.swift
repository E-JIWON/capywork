func logURL(_ day: Date) -> URL {
    // Local-time day, matching `date +%F` in hook.sh.
    let name = day.formatted(Date.ISO8601FormatStyle(timeZone: .current).year().month().day())
    return FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".capywork/log/\(name).jsonl")
}

func openSession(_ e: Employee) {
    guard let id = e.deskId, let url = URL(string: "claude://code/continue?session=\(id)") else { return NSSound.beep() }
    NSWorkspace.shared.open(url)
}

/// Global ⌃⌥⌘C via Carbon (no Accessibility permission needed).
nonisolated(unsafe) var hotKeyAction: (() -> Void)?
func registerHotKey(_ action: @escaping () -> Void) {
    hotKeyAction = action
    var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
    InstallEventHandler(GetApplicationEventTarget(), { _, _, _ in hotKeyAction?(); return noErr }, 1, &spec, nil, nil)
    var ref: EventHotKeyRef?
    RegisterEventHotKey(UInt32(kVK_ANSI_C), UInt32(controlKey | optionKey | cmdKey),
                        EventHotKeyID(signature: OSType(0x434F_4646), id: 1), GetApplicationEventTarget(), 0, &ref)
}

enum WorkState: Int, Comparable {
    case idle, working, waiting  // higher = shown in menu bar
    static func < (a: Self, b: Self) -> Bool { a.rawValue < b.rawValue }
    var label: String { ["대기", "근무 중", "결재 대기"][rawValue] }
    var nsColor: NSColor {
        [NSColor.secondaryLabelColor,
         NSColor(srgbRed: 0.85, green: 0.47, blue: 0.34, alpha: 1),  // Claude orange
         NSColor.systemRed][rawValue]
    }
    var color: Color { Color(nsColor: nsColor) }
}

struct Employee: Identifiable {
    let id: String
    let project: String
    var state = WorkState.idle
    var task = ""
    var since: Date
    var last: Date
    var title = ""      // desktop app session title, if any
    var deskId: String? // desktop app session id → clickable
    var done: Date?     // when the last turn finished
    var fails = 0       // consecutive tool failures
    var flailing: Bool { state == .working && fails >= 2 }
    var unread = false  // finished after you last looked
    var name: String { title.isEmpty ? project : title }
    var needsYou: Bool { state == .waiting || unread }
    var rank: Int { state == .waiting ? 3 : unread ? 2 : state == .working ? 1 : 0 }
    var color: Color { flailing ? .red : unread && state == .idle ? .blue : state.color }
    var label: String { flailing ? "에러 반복" : unread && state == .idle ? "새 답변" : state.label }
}

