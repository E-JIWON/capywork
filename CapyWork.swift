/// This week's work time, Monday→Sunday.
struct Grass: View {
    let history: [Date: TimeInterval]
    var body: some View {
        let cal = Calendar.current
        let today = cal.startOfDay(for: Date())
        let monday = cal.date(byAdding: .day, value: -((cal.component(.weekday, from: today) + 5) % 7), to: today)!
        let days = (0..<7).map { cal.date(byAdding: .day, value: $0, to: monday)! }
        let total = days.reduce(0.0) { $0 + (history[$1] ?? 0) }
        VStack(alignment: .leading, spacing: 6) {
            HStack {
                Text("이번 주 잔디").font(.system(size: 11, weight: .medium)).foregroundStyle(.secondary)
                Spacer()
                Text("합계 \(hm(total))").font(.system(size: 11)).monospacedDigit().foregroundStyle(.tertiary)
            }
            HStack(spacing: 6) {
                ForEach(days, id: \.self) { day in
                    VStack(spacing: 4) {
                        RoundedRectangle(cornerRadius: 4)
                            .fill(day > today ? Color.primary.opacity(0.04) : fill(history[day] ?? 0))
                            .frame(height: 22)
                            .overlay(RoundedRectangle(cornerRadius: 4)
                                .strokeBorder(Color.primary.opacity(day == today ? 0.45 : 0), lineWidth: 1))
                            .help("\(day.formatted(.dateTime.month().day().weekday())) · \(hm(history[day] ?? 0))")
                        Text(day.formatted(.dateTime.weekday(.narrow)))
                            .font(.system(size: 10, weight: day == today ? .semibold : .regular))
                            .foregroundStyle(day == today ? .primary : .tertiary)
                    }
                    .frame(maxWidth: .infinity)
                }
            }
        }
    }
    func fill(_ t: TimeInterval) -> Color {
        let m = t / 60
        guard m >= 1 else { return .primary.opacity(0.08) }
        return WorkState.working.color.opacity(m < 30 ? 0.35 : m < 60 ? 0.55 : m < 120 ? 0.8 : 1)
    }
}

