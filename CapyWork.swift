func selfTest() {
    let log = """
    {"ts":1000,"e":"SessionStart","sid":"a","cwd":"/x/nadeul"}
    {"ts":1010,"e":"UserPromptSubmit","sid":"a","cwd":"/x/nadeul","prompt":"fix login"}
    {"ts":1020,"e":"Notification","sid":"a","cwd":"/x/nadeul","msg":"Claude needs your permission to use Bash"}
    {"ts":1030,"e":"PostToolUse","sid":"a","cwd":"/x/nadeul"}
    {"ts":1070,"e":"Stop","sid":"a","cwd":"/x/nadeul"}
    {"ts":1080,"e":"Notification","sid":"a","cwd":"/x/nadeul","msg":"Claude is waiting for your input"}
    {"ts":1000,"e":"SessionStart","sid":"b","cwd":"/x/web"}
    {"ts":1100,"e":"UserPromptSubmit","sid":"b","cwd":"/x/web","prompt":"hi"}
    {"ts":1101,"e":"UserPromptSubmit","sid":"b","cwd":"/x/web","prompt":"<task-notification>done"}
    {"ts":1000,"e":"SessionStart","sid":"c","cwd":"/x/gone"}
    {"ts":1001,"e":"SessionEnd","sid":"c","cwd":"/x/gone"}
    """
    var r = parse(log, now: Date(timeIntervalSince1970: 1130))
    assert(r.orders == 3)
    assert(r.staff.first { $0.id == "b" }?.task == "hi", "system turns don't replace the task")
    assert(r.staff.count == 2, "ended session c removed")
    assert(r.staff.first { $0.id == "a" }?.state == .idle, "idle ping doesn't mean waiting")
    assert(r.staff.first { $0.id == "a" }?.done == Date(timeIntervalSince1970: 1070))
    assert(r.staff.first { $0.id == "b" }?.done == nil, "new order clears done")
    assert(r.ended.map(\.id) == ["c"], "clock-outs are reported")
    let fails = """
    {"ts":1,"e":"UserPromptSubmit","sid":"f","cwd":"/x/p","prompt":"go"}
    {"ts":2,"e":"PostToolUseFailure","sid":"f","cwd":"/x/p"}
    {"ts":3,"e":"PostToolUseFailure","sid":"f","cwd":"/x/p"}
    """
    assert(parse(fails, now: Date(timeIntervalSince1970: 4)).staff.first?.flailing == true)
    assert(parse(fails + "\n{\"ts\":4,\"e\":\"PostToolUse\",\"sid\":\"f\",\"cwd\":\"/x/p\"}", now: Date(timeIntervalSince1970: 5)).staff.first?.flailing == false, "a success resets")
    assert(r.staff.first { $0.id == "b" }?.state == .working)
    assert(r.worked == 60 + 30, "a: 1010→1070, b: 1100→now")
    r = parse(log.split(separator: "\n").prefix(3).joined(separator: "\n"), now: Date(timeIntervalSince1970: 1030))
    assert(r.staff.first?.state == .waiting)
    r = parse(log, now: Date(timeIntervalSince1970: 1130 + 4 * 3600))
    assert(r.staff.isEmpty, "stale sessions dropped")
    for p in [Pose.sleep] + (0..<4).flatMap({ [Pose.swim($0, night: true), .flail($0), .chew($0), .roll($0, urgent: true), .toss($0)] }) {
        let rows = poseRows(p)
        assert(rows.count == 15 && rows.allSatisfy { $0.count == 26 }, "\(p) must be 26×15")
    }
    print("selftest ok")
}

@main
struct CapyWorkApp: App {
    @StateObject private var office = Office()
    @StateObject private var ticker = Ticker()
    init() {
        if CommandLine.arguments.contains("--selftest") { selfTest(); exit(0) }
        NSApplication.shared.setActivationPolicy(.accessory)
    }
    var body: some Scene {
        MenuBarExtra {
            Panel(office: office)
        } label: {
            Image(nsImage: menuIcon(poses(), more: max(0, active().count - 5)))
        }
        .menuBarExtraStyle(.window)
    }

    // Busy or needs-you sessions each get a capybara; with none, one naps.
    private func active() -> [Employee] { office.report.staff.filter { $0.state != .idle || $0.unread } }

    private func poses() -> [Pose] {
        let hour = Calendar.current.component(.hour, from: Date())
        let night = hour >= 19 || hour < 5  // 야근: 7pm–5am
        let t = ticker.frame / 2  // 0.3s per frame; neglected approvals use the full 0.15s tick
        var poses: [Pose] = active().prefix(5).enumerated().map { i, e in
            switch e.state {
            case .working: return e.flailing ? .flail(t + i) : .swim(t + i, night: night)
            case .waiting:
                let urgent = Date().timeIntervalSince(e.since) > 300
                return .roll((urgent ? ticker.frame : t) + i, urgent: urgent)
            case .idle: return .chew(t + i)  // idle + unread
            }
        }
        poses += office.celebrating.map { .toss(Int(Date().timeIntervalSince($0) / 0.3)) }
        return poses.isEmpty ? [.sleep] : poses
    }
}
