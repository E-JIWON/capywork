                    Capsule().fill(pct >= 80 ? Color.red : WorkState.working.color)
                        .frame(width: max(4, g.size.width * pct / 100))
                }
            }
            .frame(height: 6)
            Text("\(Int(pct.rounded()))%").font(.system(size: 11, weight: .semibold)).monospacedDigit()
                .frame(width: 34, alignment: .trailing)
