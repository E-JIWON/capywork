struct Report {
    var staff: [Employee] = []
    var clockIn: Date?
    var orders = 0
    var worked: TimeInterval = 0
    var ended: [(id: String, at: Date)] = []
}

func parse(_ text: String, now: Date) -> Report {
    var r = Report()
    var staff: [String: Employee] = [:]
    var workStart: [String: Date] = [:]
    func punchOut(_ sid: String, _ t: Date) {
        if let w = workStart.removeValue(forKey: sid) { r.worked += t.timeIntervalSince(w) }
    }
    for line in text.split(separator: "\n") {
        guard let o = try? JSONSerialization.jsonObject(with: Data(line.utf8)) as? [String: Any],
              let ts = o["ts"] as? Double, let e = o["e"] as? String, let sid = o["sid"] as? String
        else { continue }
        let t = Date(timeIntervalSince1970: ts)
        r.clockIn = r.clockIn ?? t
        let cwd = (o["cwd"] as? String) ?? "?"
        let project = cwd.contains("/scratch-workspaces/") ? "임시 작업"
            : cwd.split(separator: "/").last.map(String.init) ?? "?"
        var s = staff[sid] ?? Employee(id: sid, project: project, since: t, last: t)
        let old = s.state
        switch e {
        case "UserPromptSubmit":
            r.orders += 1
            s.state = .working
            s.done = nil
            s.fails = 0
            // System-injected turns (<task-notification> etc.) aren't real orders.
            let p = (o["prompt"] as? String ?? "").replacingOccurrences(of: "\n", with: " ")
            if !p.hasPrefix("<") { s.task = p }
            workStart[sid] = workStart[sid] ?? t
        case "PostToolUse", "PostToolUseFailure":
            s.state = .working
            s.fails = e == "PostToolUse" ? 0 : s.fails + 1
            workStart[sid] = workStart[sid] ?? t
        case "Notification":
            // Only permission prompts count; the 60s "waiting for input" ping is just idle.
            if (o["msg"] as? String ?? "").contains("permission") { s.state = .waiting }
        case "Stop":
            s.state = .idle
            s.done = t
            punchOut(sid, t)
        case "SessionEnd":
            punchOut(sid, t)
            if staff[sid] != nil { r.ended.append((sid, t)) }
            staff[sid] = nil
            continue
        default: break  // SessionStart: just clock in
        }
        if s.state != old { s.since = t }
        s.last = t
        staff[sid] = s
    }
    for (sid, w) in workStart where staff[sid] != nil { r.worked += now.timeIntervalSince(w) }
    // ponytail: sessions killed without SessionEnd linger; drop after 3h of silence.
    r.staff = staff.values.filter { now.timeIntervalSince($0.last) < 3 * 3600 }
        .sorted { ($0.rank, $0.last) > ($1.rank, $1.last) }  // needs-you first, then most recent
    return r
}

struct Desk {
    let cli, id, title: String
    let url: URL
    let mtime: Date
    let focused: Date  // last time you opened this session in the Claude app
}

func mtime(_ u: URL) -> Date? {
    (try? FileManager.default.attributesOfItem(atPath: u.path))?[.modificationDate] as? Date
}

func readDesk(_ u: URL) -> Desk? {
    guard let data = try? Data(contentsOf: u),
          let o = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
          let cli = o["cliSessionId"] as? String, let id = o["sessionId"] as? String, let m = mtime(u)
    else { return nil }
    let focusedMs = (o["lastFocusedAt"] as? Double) ?? 0
    return Desk(cli: cli, id: id, title: o["title"] as? String ?? "", url: u, mtime: m,
                focused: Date(timeIntervalSince1970: focusedMs / 1000))
}

/// Plan usage window (5-hour or weekly).
struct Limit { var pct: Double; var resets: Date? }
struct Limits { var five: Limit?; var week: Limit? }

/// No login needed: Claude Code's statusLine hands us `rate_limits` (statusline.sh saves it),
/// and the Claude app logs 15-min usage samples (no reset times). Newest percentage wins.
func readLimits(now: Date) -> Limits {
    var out = Limits()
    var snapAt = Date.distantPast
    let home = FileManager.default.homeDirectoryForCurrentUser
    if let d = try? Data(contentsOf: home.appendingPathComponent(".capywork/limits.json")),
       let o = try? JSONSerialization.jsonObject(with: d) as? [String: Any],
       let ts = o["ts"] as? Double, let rl = o["rate_limits"] as? [String: Any] {
        snapAt = Date(timeIntervalSince1970: ts)
        for (key, kp) in [("five_hour", \Limits.five), ("seven_day", \Limits.week)] {
            guard let w = rl[key] as? [String: Any], let p = w["used_percentage"] as? Double else { continue }
            let r = (w["resets_at"] as? Double).map { Date(timeIntervalSince1970: $0) }
            let expired = r.map { $0 <= now } ?? false
            out[keyPath: kp] = Limit(pct: expired ? 0 : p, resets: expired ? nil : r)  // window rolled over
        }
    }
    if let d = try? Data(contentsOf: home.appendingPathComponent("Library/Application Support/Claude/plan-usage-history.json")),
       let o = try? JSONSerialization.jsonObject(with: d) as? [String: Any],
       let last = (o["samples"] as? [[String: Any]])?.last,
       let t = last["t"] as? Double, let u = last["u"] as? [String: Double],
       Date(timeIntervalSince1970: t / 1000) > snapAt {
        if let fh = u["fh"] { out.five = Limit(pct: fh, resets: out.five?.resets) }
        if let sd = u["sd"] { out.week = Limit(pct: sd, resets: out.week?.resets) }
    }
    return out
}

final class Office: ObservableObject {
    @Published var report = Report()
    @Published var limits = Limits()
    @Published var history: [Date: TimeInterval] = [:]  // day start → worked
    private var historyDay = Date.distantPast
    private var backfill: [Date: TimeInterval] = [:]  // pre-hook days, from backfill.py
    private var alerted = Set<String>()
    private var timer: Timer?
    private var desk: [String: Desk] = [:]  // CLI session id → desktop session
    private var seen: [String: Date] = [:]  // finishes you watched happen / opened from here
    private var lastDone: [String: Date] = [:]
    private var nagged = Set<String>()                 // approvals already re-alerted at 5 min
    private var celebrated = Set<String>()
    @Published var celebrating: [Date] = []            // when each clock-out fling started
    private var lastScan = Date.distantPast

    init() {
        reload()
        registerHotKey { [weak self] in
            // Staff is sorted needs-you first, so the first openable one is the right target.
            guard let e = self?.report.staff.first(where: { $0.deskId != nil }) else { return NSSound.beep() }
            self?.open(e)
        }
        // ponytail: 2s polling re-reads the whole day file; switch to a file watcher if it gets big.
        timer = Timer.scheduledTimer(withTimeInterval: 2, repeats: true) { [weak self] _ in self?.reload() }
    }

    func reload() {
        let today = Calendar.current.startOfDay(for: Date())
        if historyDay != today { loadHistory(today) }
        var r = parse((try? String(contentsOf: logURL(today), encoding: .utf8)) ?? "", now: Date())
        history[today] = max(r.worked, backfill[today] ?? 0)
        if r.staff.contains(where: { desk[$0.id] == nil }), Date().timeIntervalSince(lastScan) > 30 {
            scanDesktopSessions()
        }
        let watching = NSWorkspace.shared.frontmostApplication?.bundleIdentifier == "com.anthropic.claudefordesktop"
            ? desk.max { $0.value.focused < $1.value.focused }?.key : nil
        for i in r.staff.indices {
            let sid = r.staff[i].id
            guard var d = desk[sid] else { continue }  // ponytail: terminal-only sessions never count as unread
            if let m = mtime(d.url), m != d.mtime, let fresh = readDesk(d.url) { d = fresh; desk[sid] = d }
            r.staff[i].deskId = d.id
            r.staff[i].title = d.title
            guard let done = r.staff[i].done else { continue }
            // A turn that finished while you were looking at it is already read.
            if done != lastDone[sid] { lastDone[sid] = done; if sid == watching { seen[sid] = done } }
            r.staff[i].unread = r.staff[i].state == .idle && done > max(d.focused, seen[sid] ?? .distantPast)
        }
        r.staff.sort { ($0.rank, $0.last) > ($1.rank, $1.last) }
        report = r
        limits = readLimits(now: Date())
        let waiting = Set(report.staff.filter { $0.state == .waiting }.map(\.id))
        for e in report.staff where waiting.contains(e.id) && !alerted.contains(e.id) {
            notify("결재 대기 · \(e.name)", "Claude가 권한 승인을 기다리고 있어요")
        }
        alerted = waiting
        for e in report.staff where e.state == .waiting && !nagged.contains(e.id) && Date().timeIntervalSince(e.since) > 300 {
            notify("결재 5분째 대기 · \(e.name)", "귤이 빨개지고 있어요 🍊")
            nagged.insert(e.id)
        }
        nagged.formIntersection(waiting)
        // Clock-out fling: only for sessions that ended in the last few seconds.
        for end in r.ended where !celebrated.contains(end.id) {
            celebrated.insert(end.id)
            if Date().timeIntervalSince(end.at) < 10 { celebrating.append(Date()) }
        }
        celebrating.removeAll { Date().timeIntervalSince($0) > 2.4 }
    }

    func open(_ e: Employee) {
        seen[e.id] = Date()
        openSession(e)
        reload()
    }

    /// Past days never change, so read them once (and again after midnight).
    private func loadHistory(_ today: Date) {
        historyDay = today
        let cal = Calendar.current
        let url = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".capywork/backfill.json")
        if let d = try? Data(contentsOf: url), let o = try? JSONSerialization.jsonObject(with: d) as? [String: Double] {
            let f = Date.ISO8601FormatStyle(timeZone: .current).year().month().day()
            for (k, v) in o { if let day = try? f.parse(k) { backfill[cal.startOfDay(for: day)] = v } }
        }
        history = backfill
        for i in 1..<7 {
            let d = cal.date(byAdding: .day, value: -i, to: today)!
            guard let t = try? String(contentsOf: logURL(d), encoding: .utf8) else { continue }
            history[d] = max(history[d] ?? 0, parse(t, now: cal.date(byAdding: .day, value: 1, to: d)!).worked)
        }
    }

    /// The Claude desktop app keeps one JSON per Code session, linking its id to the CLI session id.
    private func scanDesktopSessions() {
        lastScan = Date()
        let root = FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent("Library/Application Support/Claude/claude-code-sessions")
        guard let files = FileManager.default.enumerator(at: root, includingPropertiesForKeys: nil) else { return }
        for case let u as URL in files where u.lastPathComponent.hasPrefix("local_") && u.pathExtension == "json" {
            if let d = readDesk(u) { desk[d.cli] = d }
        }
    }

    private func notify(_ title: String, _ body: String) {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/osascript")
        p.arguments = ["-e", "display notification \"\(body)\" with title \"\(title)\" sound name \"Glass\""]
        try? p.run()
    }
}

func hm(_ t: TimeInterval) -> String {
    let m = Int(t) / 60
    return m >= 60 ? "\(m / 60)시간 \(m % 60)분" : "\(m)분"
}

struct UsageRow: View {
    let title: String
    let limit: Limit
    var body: some View {
        let pct = min(max(limit.pct, 0), 100)
        HStack(spacing: 8) {
            Text(title).font(.system(size: 11, weight: .medium)).foregroundStyle(.secondary)
                .frame(width: 30, alignment: .leading)
            GeometryReader { g in
                ZStack(alignment: .leading) {
